// Native block surfaces from the WEB GAME'S OWN CODE and files (docs/ANDROID.md N2):
//   node tools/engine-tiles.mjs            (needs `pnpm dev`; writes engine/assets/tiles/ + tiles_gen.rs)
//   node tools/engine-tiles.mjs --check    (no browser: fails if a source, the web's surface code or
//                                           the generated Rust is out of step)
//
// What the web draws on a block face (blockMaterials.ts / voxelView.ts):
// - most blocks: a picture tile, public/textures/blocks/*.webp, that kitSurface.ts `framelessTile`
//   crops, wraps and de-inks on a canvas at runtime. Canvas work is not reproducible bit for bit
//   outside a browser, so this runs that very function in headless Edge and saves its output (WebP,
//   q 0.95: at one tile per metre the difference is invisible; PNG was 6 MB);
// - snow / grass top / gem: the AI-generated albedos, used as they are. Native reads THOSE FILES
//   (the shared asset), nothing is baked for them;
// - everything else: the procedural family maps (surface.rs = createMaterialMaps).
// Which one a face uses (needsCatalogTexture, surfaceStyle, GENERATED_BLOCK_TEXTURES, GRASS_TINT) is
// asked of the web code here and written into tiles_gen.rs, so the choice lives in one place.
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync, existsSync, readdirSync, rmSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(root, "engine/assets/tiles");
const MANIFEST = path.join(OUT, "manifest.json");
const RUST = path.join(root, "engine/crates/client/src/tiles_gen.rs");
const rel = (p) => path.relative(root, p).split(path.sep).join("/");
const sha = (file) => createHash("sha256").update(readFileSync(path.join(root, file))).digest("hex");
// source code is hashed with LF line endings: a Windows checkout (autocrlf) and CI's must agree
const codeSha = (file) => createHash("sha256").update(readFileSync(path.join(root, file), "utf8").replace(/\r\n/g, "\n")).digest("hex");
// the web code whose behaviour the bake captures: a change here means a re-bake
const CODE = ["apps/client/src/craft/kitSurface.ts", "apps/client/src/craft/blockMaterials.ts", "apps/client/src/craft/generatedBlockTextures.ts", "apps/client/src/craft/blocks.ts"];
const GRASS_TINT = [1.18, 1.3, 0.92]; // voxelView.ts GRASS_TINT default (checked below)

const camel = (family) => family.split("-").map((s) => s[0].toUpperCase() + s.slice(1)).join("");

/** tiles_gen.rs from the manifest (deterministic: --check regenerates and compares). */
function rust(manifest) {
  const names = Object.keys(manifest.tiles);
  const from = path.dirname(RUST);
  const lines = [
    "// GENERATED by tools/engine-tiles.mjs from the web game's surface code — do not edit.",
    "// Re-run `node tools/engine-tiles.mjs` (with pnpm dev) after changing a block texture or kitSurface/blockMaterials.",
    "",
    "use craftyap_core::surface::Family;",
    "",
    "/// A picture surface: the encoded image (WebP), and whether the web uploads it flipped (three's",
    "/// `flipY`: row 0 of the image lands at v = 1).",
    "pub struct Tile {",
    "    pub name: &'static str,",
    "    pub webp: &'static [u8],",
    "    pub flip_y: bool,",
    "    /// The tile's own normal and roughness/metalness maps (WebP, linear), when it has them (the AI",
    "    /// albedos). Picture tiles keep their block family's procedural maps, as the web's materials do.",
    "    pub normal: Option<&'static [u8]>,",
    "    pub roughness: Option<&'static [u8]>,",
    "}",
    "",
    "pub const TILES: &[Tile] = &[",
    ...names.map((n) => {
      const t = manifest.tiles[n];
      const inc = (f) => (f ? `Some(include_bytes!(${JSON.stringify(path.relative(from, path.join(root, f)).split(path.sep).join("/"))}))` : "None");
      return `    Tile { name: ${JSON.stringify(n)}, webp: include_bytes!(${JSON.stringify(path.relative(from, path.join(root, t.file)).split(path.sep).join("/"))}), flip_y: ${t.flipY}, normal: ${inc(t.normal?.file)}, roughness: ${inc(t.roughness?.file)} },`;
    }),
    "];",
    "",
    "/// What a face band shows.",
    "#[derive(Clone, Copy, Debug, PartialEq)]",
    "pub enum Surface {",
    "    /// `TILES[i]`.",
    "    Tile(usize),",
    "    /// A procedural family map (surface.rs).",
    "    Family(Family),",
    "}",
    "",
    "/// How the surface is tinted: not at all, by the block colour, or by a multiplier (may exceed 1).",
    "#[derive(Clone, Copy, Debug, PartialEq)]",
    "pub enum Tint {",
    "    White,",
    "    Color,",
    "    Mul([f32; 3]),",
    "}",
    "",
    "/// Per block id: (top, side, bottom) bands, as the web's materials draw them.",
    "pub const BLOCK_BANDS: &[(u8, [(Surface, Tint); 3])] = &[",
    ...manifest.blocks.map((b) => {
      const band = ({ layer, tint }) => {
        const s = layer.startsWith("family-") ? `Surface::Family(Family::${camel(layer.slice(7))})` : `Surface::Tile(${names.indexOf(layer)})`;
        const t = tint === "white" ? "Tint::White" : tint === "color" ? "Tint::Color" : `Tint::Mul([${tint.map((v) => (Number.isInteger(v) ? v + ".0" : v)).join(", ")}])`;
        return `(${s}, ${t})`;
      };
      return `    (${b.id}, [${b.bands.map(band).join(", ")}]), // ${b.key}`;
    }),
    "];",
    "",
  ];
  return lines.join("\n");
}

function stale(manifest) {
  const problems = [];
  for (const file of CODE) if (manifest.code?.[file] !== codeSha(file)) problems.push(`${file} changed`);
  const tint = readFileSync(path.join(root, "apps/client/src/craft/voxelView.ts"), "utf8").includes(`: [${GRASS_TINT.join(", ")}]`);
  if (!tint) problems.push("voxelView.ts GRASS_TINT changed (update GRASS_TINT in engine-tiles.mjs)");
  for (const [name, t] of Object.entries(manifest.tiles ?? {})) {
    if (!existsSync(path.join(root, t.source)) || sha(t.source) !== t.sourceSha256) problems.push(`${t.source} changed`);
    if (!existsSync(path.join(root, t.file)) || sha(t.file) !== t.sha256) problems.push(`${name}: ${t.file} is not the recorded file`);
    for (const extra of [t.normal, t.roughness]) if (extra && (!existsSync(path.join(root, extra.file)) || sha(extra.file) !== extra.sha256)) problems.push(`${name}: ${extra.file} changed`);
  }
  if (!existsSync(RUST) || readFileSync(RUST, "utf8").replace(/\r\n/g, "\n") !== rust(manifest)) problems.push(`${rel(RUST)} is not generated from the manifest`);
  return problems;
}

if (process.argv.includes("--check")) {
  if (!existsSync(MANIFEST)) {
    console.error("engine/assets/tiles/manifest.json missing: run `node tools/engine-tiles.mjs` (with pnpm dev)");
    process.exit(1);
  }
  const problems = stale(JSON.parse(readFileSync(MANIFEST, "utf8")));
  if (problems.length) {
    console.error("native block tiles are stale (run `node tools/engine-tiles.mjs` with pnpm dev):\n  " + problems.join("\n  "));
    process.exit(1);
  }
  console.log("native block tiles up to date");
  process.exit(0);
}

const EDGE = "C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe";
const BASE = process.env.BASE || "http://localhost:5173";
// only the bake needs a browser: --check runs without puppeteer
const { default: puppeteer } = await import("puppeteer-core");
const browser = await puppeteer.launch({ executablePath: EDGE, headless: "new", args: ["--no-sandbox"] });
try {
  const page = await browser.newPage();
  page.on("pageerror", (e) => console.log("PAGEERROR:", e.message));
  await page.goto(BASE + "/", { waitUntil: "networkidle2", timeout: 60000 });
  const baked = await page.evaluate(async (grassTint) => {
    const { framelessTile, KEEP_INK } = await import("/src/craft/kitSurface.ts");
    const { loadTexture } = await import("/src/render/textures.ts");
    const { BLOCKS, textureUrl } = await import("/src/craft/blocks.ts");
    const { needsCatalogTexture, surfaceStyle } = await import("/src/craft/blockMaterials.ts");
    const { GENERATED_BLOCK_TEXTURES } = await import("/src/craft/generatedBlockTextures.ts");
    const tiles = {};
    const blocks = [];
    for (const def of BLOCKS) {
      if (def.fluid) continue;
      const style = surfaceStyle(def.key);
      const families = style.family === "grass" ? ["grass", "grass-side", "dirt"] : [style.family, style.family, style.family];
      const featured = ["snow", "grass", "dirt", "diamond-block"].includes(def.key);
      const bands = [];
      if (needsCatalogTexture(def)) {
        // voxelView: the frameless tile on every face material, colour set to white. It is the
        // block's own picture, so it also wins over a family's generated albedo (obsidian).
        const name = "tile-" + def.texture;
        if (!tiles[name]) {
          const tex = await loadTexture(textureUrl(def));
          if (!tex) throw new Error("no texture for " + def.key);
          const tile = framelessTile(tex, KEEP_INK.has(def.texture));
          const img = tile.image;
          const c = document.createElement("canvas");
          c.width = img.width;
          c.height = img.height;
          c.getContext("2d").drawImage(img, 0, 0);
          tiles[name] = { source: "apps/client/public" + textureUrl(def), flipY: tile.flipY, width: img.width, height: img.height, webp: c.toDataURL("image/webp", 0.95) };
        }
        for (let b = 0; b < 3; b++) bands.push({ layer: name, tint: "white" });
      } else {
        for (let b = 0; b < 3; b++) {
          const family = families[b];
          const generated = GENERATED_BLOCK_TEXTURES[family];
          // BlockMaterialLibrary: the generated maps replace the procedural ones, except dirt / grass-side
          if (generated && family !== "dirt" && family !== "grass-side") {
            const name = "ai-" + family;
            if (!tiles[name]) {
              const tex = await loadTexture(generated.albedo, { repeat: true });
              if (!tex) throw new Error("no generated albedo for " + family);
              const file = (u) => "apps/client" + decodeURIComponent(new URL(u, location.href).pathname);
              tiles[name] = { source: file(generated.albedo), normal: file(generated.normal), roughness: file(generated.roughness), flipY: false, width: tex.image.width, height: tex.image.height };
            }
            // the grass top material carries GRASS_TINT (voxelView.ts), a multiplier above 1
            bands.push({ layer: name, tint: family === "grass" ? grassTint : "white" });
          } else {
            bands.push({ layer: "family-" + family, tint: featured ? "white" : "color" });
          }
        }
      }
      blocks.push({ id: def.id, key: def.key, bands });
    }
    return { tiles, blocks };
  }, GRASS_TINT);
  mkdirSync(OUT, { recursive: true });
  for (const f of readdirSync(OUT)) if (/\.(png|webp)$/.test(f)) rmSync(path.join(OUT, f));
  const tiles = {};
  for (const [name, t] of Object.entries(baked.tiles)) {
    let file = t.source;
    if (t.webp) {
      if (!t.webp.startsWith("data:image/webp")) throw new Error("this browser cannot encode WebP");
      file = rel(path.join(OUT, name + ".webp"));
      writeFileSync(path.join(root, file), Buffer.from(t.webp.split(",")[1], "base64"));
    }
    if (!existsSync(path.join(root, t.source))) throw new Error(`cannot find the source of ${name}: ${t.source}`);
    const extra = (f) => (f ? { file: f.replace(/\?.*$/, ""), sha256: sha(f.replace(/\?.*$/, "")) } : undefined);
    tiles[name] = { source: t.source, sourceSha256: sha(t.source), file, sha256: sha(file), flipY: t.flipY, width: t.width, height: t.height, normal: extra(t.normal), roughness: extra(t.roughness) };
  }
  const manifest = {
    version: 1,
    note: "GENERATED by tools/engine-tiles.mjs from the web game's own surface code; do not edit",
    code: Object.fromEntries(CODE.map((f) => [f, codeSha(f)])),
    tiles,
    blocks: baked.blocks,
  };
  writeFileSync(MANIFEST, JSON.stringify(manifest, null, 1) + "\n");
  writeFileSync(RUST, rust(manifest));
  const problems = stale(manifest);
  if (problems.length) throw new Error(problems.join("; "));
  console.log(`${Object.keys(tiles).length} surfaces for ${baked.blocks.length} blocks → engine/assets/tiles + ${rel(RUST)}`);
} finally {
  await browser.close();
}
