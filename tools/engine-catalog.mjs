// pnpm engine:catalog [--check] (run with tsx: it imports the TypeScript sources) — the block catalog for the Rust engine, GENERATED from the web's
// apps/client/src/craft/blocks.ts (the one source of truth: ids are persisted, never renumbered).
// Writes engine/crates/core/src/blocks_gen.rs; --check (CI) fails when it is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { BLOCKS, SOLID_ID } from "../apps/client/src/craft/blocks.ts";
import { CUBE, KIT_CUBE, ROUND, isFullCubeShape } from "../packages/shared/src/index.ts";
import { BLOCK_GROUPS, blockGroup } from "../apps/client/src/craft/inventory.ts";
import { PICKAXE } from "../apps/client/src/craft/toolDefinitions.ts";

const out = fileURLToPath(new URL("../engine/crates/core/src/blocks_gen.rs", import.meta.url));
const str = (s) => JSON.stringify(s); // a JSON string literal is a valid Rust string literal here
const rgb = (hex) => {
  const m = /^#([0-9a-f]{6})$/i.exec(hex);
  if (!m) throw new Error(`colour ${hex} is not #rrggbb`);
  const n = parseInt(m[1], 16);
  return `[${(n >> 16) & 255}, ${(n >> 8) & 255}, ${n & 255}]`;
};
const rows = [...BLOCKS].sort((a, b) => a.id - b.id).map((b) =>
  `    BlockDef { id: ${b.id}, key: ${str(b.key)}, name: ${str(b.name)}, ko: ${str(b.ko)}, texture: ${str(b.texture)}, color: ${rgb(b.color)}, hardness: ${Number(b.hardness).toFixed(3)}, drops: ${b.drops ? `Some(${str(b.drops)})` : "None"}, emissive: ${!!b.emissive}, no_stud: ${!!b.noStud}, see_through: ${!!b.seeThrough}, fluid: ${!!b.fluid} },`);
const solid = Array.from(SOLID_ID).map((v) => (v ? "true" : "false"));
const fullCube = Array.from({ length: 256 }, (_, i) => (isFullCubeShape(i) ? "true" : "false"));
const text = `// GENERATED by tools/engine-catalog.mjs from apps/client/src/craft/blocks.ts — do not edit.
// Regenerate with \`pnpm engine:catalog\`; CI fails when this is stale.

/// One catalog block (\`BlockDef\` in blocks.ts). Ids are persisted in saves: never renumbered.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct BlockDef {
    pub id: u8,
    pub key: &'static str,
    pub name: &'static str,
    pub ko: &'static str,
    pub texture: &'static str,
    /// The 3D brick colour (sRGB).
    pub color: [u8; 3],
    pub hardness: f32,
    pub drops: Option<&'static str>,
    pub emissive: bool,
    pub no_stud: bool,
    pub see_through: bool,
    pub fluid: bool,
}

pub const BLOCKS: &[BlockDef] = &[
${rows.join("\n")}
];

/// \`SOLID_ID\`: stops bodies, rays and neighbours' faces (not air, not water).
pub const SOLID: [bool; 256] = [${solid.join(", ")}];

/// Shape codes (@robo/shared blockShapes.ts; persisted, never renumbered).
pub const CUBE: u8 = ${CUBE};
pub const ROUND: u8 = ${ROUND};
pub const KIT_CUBE: u8 = ${KIT_CUBE};
/// \`isFullCubeShape\` per shape code.
pub const FULL_CUBE: [bool; 256] = [${fullCube.join(", ")}];
`;
// the bag's categories (inventory.ts BLOCK_GROUPS + blockGroup), for the native client only: it
// lives in the client crate, outside the wasm build's source hash (UI data, not the core's)
const groupsOut = fileURLToPath(new URL("../engine/crates/client/src/groups_gen.rs", import.meta.url));
const keys = [PICKAXE.id, ...[...BLOCKS].sort((a, b) => a.id - b.id).map((b) => b.key)];
// the web's power-plant parts (science mode) have no native counterpart yet: no empty 부품 tab in the app
const WEB_ONLY_GROUPS = new Set(["frames", "parts"]);
const groupsText = `// GENERATED by tools/engine-catalog.mjs from apps/client/src/craft/inventory.ts — do not edit.
// Regenerate with \`pnpm engine:catalog\`; CI fails when this is stale.

/// The bag's tabs in order: (id, Korean label, English label).
pub const BAG_GROUPS: &[(&str, &str, &str)] = &[
${BLOCK_GROUPS.filter((g) => !WEB_ONLY_GROUPS.has(g.id)).map((g) => `    (${str(g.id)}, ${str(g.ko)}, ${str(g.en)}),`).join("\n")}
];
/// Each item's tab (blockGroup): (item key, group id). Items not listed have no tab but "all".
pub const ITEM_GROUP: &[(&str, &str)] = &[
${keys.filter((k) => blockGroup(k)).map((k) => `    (${str(k)}, ${str(blockGroup(k))}),`).join("\n")}
];
/// The starter tool (toolDefinitions.ts PICKAXE): its item key and names.
pub const PICKAXE_KEY: &str = ${str(PICKAXE.id)};
pub const PICKAXE_NAME: &str = ${str(PICKAXE.name)};
`;
if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(out, "utf8").replace(/\r\n/g, "\n"); } catch { /* missing = stale */ }
  if (current !== text) {
    console.error("engine/crates/core/src/blocks_gen.rs is stale: run `pnpm engine:catalog`");
    process.exit(1);
  }
  let groups = "";
  try { groups = readFileSync(groupsOut, "utf8").replace(/\r\n/g, "\n"); } catch { /* missing = stale */ }
  if (groups !== groupsText) {
    console.error("engine/crates/client/src/groups_gen.rs is stale: run `pnpm engine:catalog`");
    process.exit(1);
  }
  console.log("engine block catalog matches blocks.ts");
} else {
  writeFileSync(out, text);
  writeFileSync(groupsOut, groupsText);
  console.log(`engine block catalog: ${rows.length} blocks`);
}
