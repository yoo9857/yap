// raw/*.png (Codex, 1024 px, transparent) → apps/client/public/ui/quiz/*.webp: each picture is
// trimmed to its content with an even margin, scaled to the size the quiz draws it at (× 2 for
// dense screens) and encoded as WebP in headless Edge (no cwebp / ImageMagick needed).
//
//   node assets/fire-quiz/build.mjs
//
// It also writes apps/client/src/craft/fire/quizArt.ts — the list of pictures that exist. The
// quiz only plays rounds whose pictures are all there, so a pack that is still being generated
// (image generation has a usage limit) is a shorter quiz, never a broken picture.
// After a rebuild bump QUIZ_ART_V in apps/client/src/craft/fire/fireQuiz.ts.
// `fire-bin` is NOT trimmed: the "where do you aim" round's spots are measured on its full canvas.
import { createRequire } from "node:module";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "../..");
const OUT = join(ROOT, "apps/client/public/ui/quiz");
const puppeteer = createRequire(join(ROOT, "package.json"))("puppeteer-core");
const EDGE = "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe";
/** Longest side, in px. */
const SIZE = (name) => (name === "ui-board" ? 1400 : name.startsWith("ui-") ? 256 : name === "fire-bin" || name === "fire-big" ? 640 : name === "medal" || name === "cheer" || name === "think" ? 360 : 512);
mkdirSync(OUT, { recursive: true });

const browser = await puppeteer.launch({ executablePath: EDGE, headless: "new", args: ["--no-sandbox"] });
const page = await browser.newPage();
let total = 0;
for (const file of readdirSync(join(HERE, "raw")).filter((f) => f.endsWith(".png")).sort()) {
  const name = file.slice(0, -4);
  const png = readFileSync(join(HERE, "raw", file)).toString("base64");
  const webp = await page.evaluate(async (png, size, trim) => {
    const img = new Image();
    img.src = `data:image/png;base64,${png}`;
    await img.decode();
    const full = document.createElement("canvas");
    full.width = img.naturalWidth; full.height = img.naturalHeight;
    const fx = full.getContext("2d");
    fx.drawImage(img, 0, 0);
    let x0 = 0, y0 = 0, x1 = full.width, y1 = full.height;
    if (trim) {
      // the content's box (alpha over a faint threshold), squared and given a 4 % margin
      const data = fx.getImageData(0, 0, full.width, full.height).data;
      x0 = full.width; y0 = full.height; x1 = 0; y1 = 0;
      for (let y = 0; y < full.height; y++) for (let x = 0; x < full.width; x++) {
        if (data[(y * full.width + x) * 4 + 3] > 12) { if (x < x0) x0 = x; if (x > x1) x1 = x; if (y < y0) y0 = y; if (y > y1) y1 = y; }
      }
      if (trim !== "tight") { // (the board keeps its own shape and no margin: it is a 9-slice frame)
        const side = Math.max(x1 - x0, y1 - y0) * 1.08, cx = (x0 + x1) / 2, cy = (y0 + y1) / 2;
        x0 = cx - side / 2; x1 = cx + side / 2; y0 = cy - side / 2; y1 = cy + side / 2;
      } else { x1 += 1; y1 += 1; }
    }
    const scale = Math.min(1, size / Math.max(x1 - x0, y1 - y0));
    const out = document.createElement("canvas");
    out.width = Math.round((x1 - x0) * scale); out.height = Math.round((y1 - y0) * scale);
    const ox = out.getContext("2d");
    ox.imageSmoothingQuality = "high";
    ox.drawImage(full, x0, y0, x1 - x0, y1 - y0, 0, 0, out.width, out.height);
    return { data: out.toDataURL("image/webp", 0.88).split(",")[1], w: out.width, h: out.height };
  }, png, SIZE(name), name === "fire-bin" ? false : name === "ui-board" ? "tight" : true);
  const bytes = Buffer.from(webp.data, "base64");
  writeFileSync(join(OUT, `${name}.webp`), bytes);
  total += bytes.length;
  console.log(`${name}.webp  ${webp.w}x${webp.h}  ${(bytes.length / 1024).toFixed(0)} KB`);
}
await browser.close();
const built = readdirSync(OUT).filter((f) => f.endsWith(".webp")).map((f) => f.slice(0, -5)).sort();
writeFileSync(join(ROOT, "apps/client/src/craft/fire/quizArt.ts"),
  `// GENERATED by assets/fire-quiz/build.mjs — the quiz pictures that exist in public/ui/quiz.\n// Do not edit: generate the missing pictures (assets/fire-quiz/generate.mjs) and build again.\nexport const QUIZ_ART: readonly string[] = ${JSON.stringify(built)};\n`);
console.log(`${built.length} pictures listed in quizArt.ts`);
console.log(`total ${(total / 1024).toFixed(0)} KB`);
