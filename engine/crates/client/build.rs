//! Compiles in the web's block icons (`apps/client/public/textures/blocks/*.webp`, what the web's
//! hotbar and bag show) as `ICONS: &[(&str, &[u8])]` — the texture name and the file. Generated from
//! the folder at build time, so a new block's icon reaches the app with no list to keep in step.

use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    let dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("../../../apps/client/public/textures/blocks");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut names: Vec<(String, PathBuf)> = std::fs::read_dir(&dir)
        .map(|it| {
            it.filter_map(Result::ok)
                .map(|e| e.path())
                .filter(|p| p.extension().is_some_and(|x| x == "webp"))
                .filter_map(|p| Some((p.file_stem()?.to_str()?.to_owned(), p.canonicalize().ok()?)))
                .collect()
        })
        .unwrap_or_default();
    names.sort();
    let mut out = String::from("/// The web's block icons: (texture name, WebP file). GENERATED by build.rs.\npub const ICONS: &[(&str, &[u8])] = &[\n");
    for (name, path) in &names {
        // a raw string literal: Windows paths keep their backslashes
        let _ = writeln!(out, "    ({name:?}, include_bytes!(r\"{}\")),", path.display().to_string().trim_start_matches(r"\\?\"));
    }
    out.push_str("];\n");
    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("icons_gen.rs");
    std::fs::write(dest, out).expect("write icons_gen.rs");
    sounds();
}

/// The web's sound clips (`apps/client/public/audio/sfx/*.mp3`) and their manifest (bank → files).
fn sounds() {
    let dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("../../../apps/client/public/audio/sfx");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut clips: Vec<(String, PathBuf)> = std::fs::read_dir(&dir)
        .map(|it| {
            it.filter_map(Result::ok)
                .map(|e| e.path())
                .filter(|p| p.extension().is_some_and(|x| x == "mp3"))
                .filter_map(|p| Some((p.file_name()?.to_str()?.to_owned(), p.canonicalize().ok()?)))
                .collect()
        })
        .unwrap_or_default();
    clips.sort();
    let manifest = dir.join("manifest.json").canonicalize().map(|p| p.display().to_string()).unwrap_or_default();
    let json = std::fs::read_to_string(dir.join("manifest.json")).unwrap_or_else(|_| "{}".into());
    let mut banks: Vec<String> = Vec::new();
    // the bank names, in the manifest's order ("name": [ … ])
    for line in json.lines() {
        let t = line.trim();
        if let Some(rest) = t.strip_prefix('"') {
            if let Some((name, tail)) = rest.split_once('"') {
                if tail.trim_start().starts_with(':') {
                    banks.push(name.to_owned());
                }
            }
        }
    }
    let mut out = String::from("/// The web's sound clips: (file name, MP3). GENERATED by build.rs.\npub const CLIPS: &[(&str, &[u8])] = &[\n");
    for (name, path) in &clips {
        let _ = writeln!(out, "    ({name:?}, include_bytes!(r\"{}\")),", path.display().to_string().trim_start_matches(r"\\?\"));
    }
    out.push_str("];\n/// The manifest (bank → files).\n");
    let _ = writeln!(out, "pub const MANIFEST: &str = include_str!(r\"{}\");", manifest.trim_start_matches(r"\\?\"));
    let _ = writeln!(out, "/// The bank names.\npub const BANK_NAMES: &[&str] = &{banks:?};");
    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("sounds_gen.rs");
    std::fs::write(dest, out).expect("write sounds_gen.rs");
}
